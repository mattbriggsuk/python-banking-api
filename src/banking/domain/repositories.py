from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol

from banking.domain.models import Account, Customer, StoredSession


class CustomerRepository(Protocol):
    def save(self, customer: Customer, pin_hash: str) -> Customer: ...
    def get_customer(self, customer_number: str) -> Customer | None: ...
    def get_customer_by_email(self, email: str) -> Customer | None: ...
    def get_pin_hash(self, customer_number: str) -> str | None: ...


class AccountRepository(Protocol):
    def transaction(self) -> AbstractContextManager[None]:
        """Serialize a complete read/validate/write operation, including transfers."""
        ...

    def get_account(self, account_number: str) -> Account | None: ...
    def get_customer_accounts(self, customer_number: str) -> list[Account]: ...
    def save(self, account: Account) -> Account: ...
    def transfer_balance(self, from_account: Account, to_account: Account) -> None: ...


class SessionRepository(Protocol):
    def save(self, token: str, session: StoredSession) -> None: ...
    def get(self, token: str) -> StoredSession | None: ...
    def delete(self, token: str) -> None: ...
    def delete_expired(self, now: datetime) -> None: ...
