from typing import Protocol

from banking.domain.enums import AccountType
from banking.domain.models import (
    Account,
    Customer,
    CustomerRegistration,
    Transaction,
    TransferResult,
    UserSession,
)


class CustomerService(Protocol):
    def register(self, customer: Customer) -> CustomerRegistration: ...
    def get_customer(self, session: UserSession, customer_number: str) -> Customer: ...
    def get_customer_accounts(
        self, session: UserSession, customer_number: str
    ) -> list[Account]: ...


class AccessService(Protocol):
    def login(self, identifier: str, pin: str) -> UserSession: ...
    def start_session(self, customer_number: str) -> str: ...
    def authenticated_session(self, authorization: str | None) -> UserSession: ...
    def logout(self, session: UserSession) -> None: ...


class AccountService(Protocol):
    def create(
        self, session: UserSession, account_type: AccountType = AccountType.CURRENT
    ) -> Account: ...
    def close(self, session: UserSession, account_number: str) -> Account: ...
    def deposit(self, session: UserSession, transaction: Transaction) -> Account: ...
    def withdraw(self, session: UserSession, transaction: Transaction) -> Account: ...
    def transfer(self, session: UserSession, transaction: Transaction) -> TransferResult: ...
